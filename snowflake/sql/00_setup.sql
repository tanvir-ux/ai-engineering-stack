-- Meridian knowledge copilot: Snowflake objects. NOT executed against a live account.
-- Run as a role that can create warehouses and databases (for example SYSADMIN).
CREATE WAREHOUSE IF NOT EXISTS MERIDIAN_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS MERIDIAN;
CREATE SCHEMA IF NOT EXISTS MERIDIAN.RAW;
CREATE SCHEMA IF NOT EXISTS MERIDIAN.ANALYTICS;

CREATE ROLE IF NOT EXISTS MERIDIAN_COPILOT;
GRANT USAGE ON WAREHOUSE MERIDIAN_WH TO ROLE MERIDIAN_COPILOT;
GRANT USAGE ON DATABASE MERIDIAN TO ROLE MERIDIAN_COPILOT;
GRANT USAGE ON SCHEMA MERIDIAN.RAW TO ROLE MERIDIAN_COPILOT;
GRANT USAGE ON SCHEMA MERIDIAN.ANALYTICS TO ROLE MERIDIAN_COPILOT;
