-- Internal stage plus Parquet load of the gold files produced by the PySpark job.
-- Upload from your machine with SnowSQL or the Snowflake CLI:
--   PUT file://artifacts/gold/chunks.parquet  @MERIDIAN.RAW.GOLD_STAGE AUTO_COMPRESS=FALSE;
--   PUT file://artifacts/gold/tickets.parquet @MERIDIAN.RAW.GOLD_STAGE AUTO_COMPRESS=FALSE;
USE SCHEMA MERIDIAN.RAW;

CREATE OR REPLACE FILE FORMAT PARQUET_FMT TYPE = PARQUET USE_LOGICAL_TYPE = TRUE;

CREATE OR REPLACE STAGE GOLD_STAGE FILE_FORMAT = PARQUET_FMT;

CREATE OR REPLACE TABLE CHUNKS_LOAD (
  CHUNK_ID        STRING,
  DOC_ID          STRING,
  CHUNK_INDEX     NUMBER,
  TITLE           STRING,
  CLASSIFICATION  STRING,
  DEPARTMENT      STRING,
  TEXT            STRING,
  CONTENT_HASH    STRING,
  WORD_COUNT      NUMBER,
  EMBEDDING       ARRAY,
  EMBEDDING_MODEL STRING,
  HAS_NUMBERS     BOOLEAN
);

COPY INTO CHUNKS_LOAD
  FROM @GOLD_STAGE/chunks.parquet
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  ON_ERROR = 'ABORT_STATEMENT';

CREATE OR REPLACE TABLE TICKETS (
  TICKET_ID   STRING,
  REQUESTER   STRING,
  CATEGORY    STRING,
  PRIORITY    STRING,
  STATUS      STRING,
  CREATED_AT  TIMESTAMP_NTZ,
  RESOLVED_AT TIMESTAMP_NTZ,
  SUMMARY     STRING,
  INGESTED_AT TIMESTAMP_NTZ
);

COPY INTO TICKETS
  FROM @GOLD_STAGE/tickets.parquet
  MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
  ON_ERROR = 'ABORT_STATEMENT';
