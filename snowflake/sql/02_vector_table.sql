-- Native VECTOR column (384 floats) built from the Parquet ARRAY column.
USE SCHEMA MERIDIAN.RAW;

CREATE OR REPLACE TABLE CHUNKS (
  CHUNK_ID        STRING NOT NULL,
  DOC_ID          STRING NOT NULL,
  TITLE           STRING,
  CLASSIFICATION  STRING NOT NULL,
  DEPARTMENT      STRING,
  TEXT            STRING NOT NULL,
  EMBEDDING       VECTOR(FLOAT, 384) NOT NULL,
  EMBEDDING_MODEL STRING
);

INSERT INTO CHUNKS
SELECT
  CHUNK_ID, DOC_ID, TITLE, CLASSIFICATION, DEPARTMENT, TEXT,
  EMBEDDING::VECTOR(FLOAT, 384),
  EMBEDDING_MODEL
FROM CHUNKS_LOAD;
